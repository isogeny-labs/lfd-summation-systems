"""summary.json from rows.jsonl and rows-s3-binary.jsonl (the binary m-summand systems rebuilt from parameters)."""
import collections
import json
from pathlib import Path

D = Path(__file__).resolve().parent
rows = [json.loads(l) for l in open(D / 'rows.jsonl')]
extra = {json.loads(l)['id']: json.loads(l) for l in open(D / 'rows-s3-binary.jsonl')}
beyond = {}
if (D / 'rows-s6-cap9000.jsonl').exists():   # added after the frozen cap of 3000 points; labelled
    beyond = {json.loads(l)['id']: json.loads(l) for l in open(D / 'rows-s6-cap9000.jsonl')}
for r in rows:
    b = beyond.get(r['id'])
    if b and r.get('sd_drl') is None and b.get('gb_drl') is not None:
        r.update(gb_drl=b['gb_drl'], gb_grlex=b['gb_grlex'], hf_drl=b['hf_drl'], beyond_cap=True)
        r['sd_drl'], r['sd_grlex'] = max(r['lfd'], b['gb_drl']), max(r['lfd'], b['gb_grlex'])
        r['tag'] = 'computed'
    e = extra.get(r['id'])
    if e and r.get('sd_drl') is None:
        assert e['points_sha256_ok'] and e['lfd'] == r['lfd'] and e['points'] == r['points']
        r.update(gb_drl=e['gb_drl'], gb_grlex=e['gb_grlex'], hf_drl=e['hf_drl'], rebuilt=True)
        r['sd_drl'], r['sd_grlex'] = max(r['lfd'], e['gb_drl']), max(r['lfd'], e['gb_grlex'])
        r['tag'] = 'computed'
    if r.get('sd_drl') is None and r['lfd'] is None and r['points'] == 0:
        r['tag'] = 'unit'          # sd = LFD whatever the exact value is
    if r.get('sd_drl') is not None and 'sd_grlex' not in r:
        r['sd_grlex'] = r['sd_drl'] if r['tag'] in ('unit', 'count', 'cube') else max(r['lfd'], r['gb_grlex'])

exact = [r for r in rows if r['lfd'] is not None]
computed = [r for r in rows if r.get('gb_drl') is not None and r['lfd'] is not None]
by_set = collections.defaultdict(collections.Counter)
for r in exact:
    by_set[r['set']][r['tag'] or 'unresolved'] += 1
above = [r for r in computed if r['gb_drl'] > r['lfd'] or r['gb_grlex'] > r['lfd']]
summary = dict(
    systems=len(rows), exact_lfd_systems=len(exact),
    tags_by_set={k: dict(v) for k, v in sorted(by_set.items())},
    tags_total=dict(collections.Counter(r['tag'] or 'unresolved' for r in exact)),
    gb_computed=len(computed),
    gb_minus_lfd_drl=dict(sorted(collections.Counter(r['gb_drl'] - r['lfd'] for r in computed).items())),
    gb_minus_lfd_grlex=dict(sorted(collections.Counter(r['gb_grlex'] - r['lfd'] for r in computed).items())),
    sd_equals_lfd_drl=sum(1 for r in exact if r.get('sd_drl') == r['lfd']),
    sd_known_drl=sum(1 for r in exact if r.get('sd_drl') is not None),
    sd_above_lfd=[dict(set=r['set'], id=r['id'], family=r['family'], m=r['m'], k=r['k'], r=r['r'], points=r['points'],
                       lfd=r['lfd'], gb_drl=r['gb_drl'], gb_grlex=r['gb_grlex'], hf=r['hf_drl']) for r in above],
    unresolved=[dict(set=r['set'], id=r['id'], lfd=r['lfd'], points=r['points'], r=r['r'],
                     count_bound=r['count_bound']) for r in exact if r.get('sd_drl') is None],
    tag_violations=sum(1 for r in rows if r.get('tag_violation')),
    zeta_equals_field_enumeration=dict(collections.Counter(r['zeta_equals_field_enumeration'] for r in rows
                                                           if 'zeta_equals_field_enumeration' in r)),
    deep=[dict(id=r['id'], k=r['k'], p=r['p'], points=r['points'], lfd=r['lfd'], gb_drl=r.get('gb_drl'),
               gb_grlex=r.get('gb_grlex'), tag=r['tag'], sd_drl=r.get('sd_drl')) for r in rows if r['set'] == 'S7'],
    max_gb_by_set={s: max((r['gb_drl'] for r in computed if r['set'] == s), default=None)
                   for s in sorted({r['set'] for r in computed})},
)
GROUPS = [('Sweep, prime and binary (Sec.~\\ref{sec:sweep})', ('S1',)),
          ('Two summands, $k=8,9$ (Sec.~\\ref{sec:depth89})', ('S2',)),
          ('Two summands, $k=10$--$14$ (Sec.~\\ref{sec:depth14})', ('S7',)),
          ('Direct $m$-summand, prime, $m=2,\\ldots,8$ (Sec.~\\ref{sec:msummands})', ('S4',)),
          ('Three to five summands, prime and binary', ('S3', 'S3pod')),
          ('Binary, $m=2,3$ (Sec.~\\ref{sec:sweep})', ('S5',)),
          ('Binary to dimension $16$ (Sec.~\\ref{sec:binarydeep})', ('S6',))]
lines = []
for label, sets in GROUPS:
    ex = [r for r in exact if r['set'] in sets]
    c = collections.Counter(r['tag'] or 'open' for r in ex)
    comp = [r for r in ex if r.get('gb_drl') is not None]
    assert c['open'] == 0, (label, c)
    lines.append('%s & %d & %d & %d & %s & %d\\\\' % (label, c['unit'], c['count'], c['computed'],
                 max((r['gb_drl'] for r in comp), default='--'),
                 sum(1 for r in ex if r.get('sd_drl') is not None and r['sd_drl'] > r['lfd'])))
known = [r for r in exact if r.get('sd_drl') is not None]
tex = ['% generated by experiments/ic-solving-degree/summarize.py; do not edit',
       '\\newcommand{\\SDSYSTEMS}{%s}' % f"{len(exact):,}".replace(',', '{,}'),
       '\\newcommand{\\SDKNOWN}{%s}' % f"{len(known):,}".replace(',', '{,}'),
       '\\newcommand{\\SDEQUAL}{%s}' % f"{sum(1 for r in known if r['sd_drl'] == r['lfd']):,}".replace(',', '{,}'),
       '\\newcommand{\\SDUNIT}{%s}' % f"{sum(1 for r in known if r['tag'] == 'unit'):,}".replace(',', '{,}'),
       '\\newcommand{\\SDCOUNT}{%s}' % f"{sum(1 for r in known if r['tag'] == 'count'):,}".replace(',', '{,}'),
       '\\newcommand{\\SDCOMPUTED}{%s}' % f"{sum(1 for r in known if r['tag'] == 'computed'):,}".replace(',', '{,}'),
       '\\newcommand{\\SDOPEN}{%d}' % (len(exact) - len(known)),
       '\\newcommand{\\SDTABLEROWS}{%' , *lines, '}']
(D.parents[1] / 'paper' / 'solving-degree-data.tex').write_text('\n'.join(tex) + '\n')
(D / 'rows-merged.jsonl').write_text(''.join(json.dumps(r, sort_keys=True) + '\n' for r in rows))
(D / 'summary.json').write_text(json.dumps(summary, indent=1, sort_keys=True))
print(json.dumps({k: v for k, v in summary.items() if k not in ('deep',)}, indent=1))
