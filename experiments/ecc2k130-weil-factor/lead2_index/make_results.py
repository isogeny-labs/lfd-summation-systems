#!/usr/bin/env python3
"""Merge index_hnf.out (PARI) and index_check.out (pure Python) into RESULTS.md; checks exact agreement."""
import re
gp = {}
for line in open('index_hnf.out'):
    if re.match(r'^\d+\|', line):
        f = line.strip().split('|')
        gp[int(f[0])] = dict(o2=f[1], U=int(f[2]), fac=f[3], idx=int(f[4]), ok=f[5], snf=f[6], zeta=f[7], unit=f[8], fO=f[9], sqf=f[10])
py = {}
for line in open('index_check.out'):
    if re.match(r'^\d+\|', line):
        f = line.strip().split('|')
        py[int(f[0])] = dict(U=int(f[1]), idx=int(f[3]), ok=f[4], ranks=f[5], exp=f[6], zeta=f[7], struct=f[8])
field7 = [l.strip() for l in open('index_hnf.out') if l.startswith('ell=7 field')]
out = ["# Lead 2 results: [O_F (x) Z[zeta_ell] : Z[pi, pibar]] for x^2+x+2",
       "",
       "Generated by `make_results.py` from `index_hnf.out` (PARI/GP exact HNF + SNF, `index_hnf.gp`) and",
       "`index_check.out` (pure-Python modular HNF + F_p ranks + exponent test, `index_check.py`).",
       "For ell != 7 the ambient ring is O_K, K = Q(zeta_ell, sqrt-7). 1 = true, 0 = false.",
       "",
       "| ell | ord_ell(2) | U_ell | factorization of abs(U_ell) | squarefree | digits of index | index = abs(U)^(ell-2) (PARI) | SNF = (Z/abs(U))^(ell-2) (PARI) | abs(U)·O_K ⊆ R | zeta ∈ R | U = ±1 | Python index (equal to PARI?) | Python: F_p-rank = ell for all p, exponent divides abs(U) |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
bad = 0
for ell in sorted(gp):
    g = gp[ell]; f = abs(g['U'])
    holds = g['idx'] == f ** (ell - 2)
    bad += (not holds) or g['ok'] != '1' or g['snf'] != '1' or g['zeta'] != g['unit'] or g['fO'] != '1'
    if ell in py:
        p = py[ell]; agree = p['idx'] == g['idx'] and p['U'] == g['U']
        bad += not agree
        pys = f"{'1' if agree else 'MISMATCH'}"
        pst = p['struct']
    else:
        pys, pst = "n/a (ell > 61)", "n/a"
    fac = g['fac'].replace('Mat(', '').replace(')', '')
    out.append(f"| {ell} | {g['o2']} | {g['U']} | {fac} | {g['sqf']} | {len(str(g['idx']))} | {int(holds)} | {g['snf']} | {g['fO']} | {g['zeta']} | {g['unit']} | {pys} | {pst} |")
out += ["", "ell = 7 inside the field Q(zeta_7) (not the tensor algebra; outside the theorem, see PROOF.md section 5):", ""]
out += ["    " + l for l in field7]
out += ["", f"Rows checked: {len(gp)} (PARI, primes 3..113), {len(py)} also by Python (primes 3..61). Disagreements or formula failures: {bad}.",
        "", "No U_ell for ell <= 113 is non-squarefree (also `lemma_checks.out`: none for ell <= 200), so the prime-power case is",
        "tested on the general (s, q) family in `general_tq.out` (316 non-squarefree cases, index formula holds in all 840 cases)."]
open('RESULTS.md', 'w').write('\n'.join(out) + '\n')
print("bad =", bad)
